function t(key, vars) {
  const lang = typeof currentLanguage === "function" ? currentLanguage() : localStorage.getItem("pingwatch-language") || "en";
  const table = I18N[lang] || I18N.en;
  let text = table[key] || I18N.en[key] || key;
  if (vars) {
    Object.entries(vars).forEach(([name, value]) => {
      text = text.replaceAll("{" + name + "}", String(value));
    });
  }
  return text;
}

function langMeta(id) {
  return I18N_LANGS.find((item) => item.id === id) || I18N_LANGS.find((item) => item.id === "en");
}

function applyI18n() {
  const lang = typeof currentLanguage === "function" ? currentLanguage() : localStorage.getItem("pingwatch-language") || "en";
  const meta = langMeta(lang);
  document.documentElement.lang = meta.id;
  document.documentElement.dir = meta.dir || "ltr";
  document.querySelectorAll("[data-i18n]").forEach((node) => {
    node.textContent = t(node.getAttribute("data-i18n"));
  });
  document.querySelectorAll("[data-i18n-placeholder]").forEach((node) => {
    node.placeholder = t(node.getAttribute("data-i18n-placeholder"));
  });
  document.querySelectorAll("[data-i18n-title]").forEach((node) => {
    node.title = t(node.getAttribute("data-i18n-title"));
  });
  document.querySelectorAll("[data-i18n-aria]").forEach((node) => {
    node.setAttribute("aria-label", t(node.getAttribute("data-i18n-aria")));
  });
  document.querySelectorAll("select[data-i18n-options]").forEach((select) => {
    Array.from(select.options).forEach((option) => {
      const key = option.dataset.i18n;
      if (key) option.textContent = t(key);
    });
  });
}

function fillLanguageSelects() {
  const current =
    typeof currentLanguage === "function" ? currentLanguage() : localStorage.getItem("pingwatch-language") || "en";
  document.querySelectorAll("#lang-select, #appearance-language").forEach((select) => {
    const selected = select.value || current;
    select.innerHTML = I18N_LANGS.map((item) => `<option value="${item.id}">${item.label}</option>`).join("");
    select.value = I18N_LANGS.some((item) => item.id === selected) ? selected : "en";
  });
}
